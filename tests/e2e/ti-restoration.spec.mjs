import {test,expect} from '@playwright/test';
const ready=async page=>{await page.goto('/?debug');await page.waitForFunction(()=>window.__hansch?.app.tiReady&&window.__hansch?.stage);};
const famotidine=async page=>{await page.locator('#search').fill('famotidine');await page.locator('#search').press('Enter');await expect(page.locator('#d-name')).toHaveText('famotidine');};
test('idle index loading restores live inquiry encoding and lazy ranked tools',async({page})=>{
 const requests=[],errors=[];page.on('request',r=>requests.push(new URL(r.url()).pathname));page.on('pageerror',e=>errors.push(e.message));
 await ready(page);
 expect(requests.some(p=>p.endsWith('/data/ti/live.json'))).toBe(true);
 expect(requests.some(p=>p.endsWith('/fragments/ti-body.html'))).toBe(false);
 await page.click('#inquiry-start');await page.waitForFunction(()=>window.__hansch.anim.t===1);await famotidine(page);
 const before=await page.evaluate(()=>Array.from(__hansch.stage.points.instanceColor.array));
 await page.selectOption('#color-by','ti');
 await expect(page.locator('#ti-live')).toBeVisible();await expect(page.locator('#ti-live')).toContainText('2.27');
 await expect(page.locator('#ti-live')).toContainText('measured aggregate');
 await expect(page.locator('#legend')).toContainText(/index|activity|hERG/i);
 expect(await page.evaluate(()=>Array.from(__hansch.stage.points.instanceColor.array))).not.toEqual(before);
 await page.selectOption('#ax-y','ti');await page.waitForFunction(()=>__hansch.anim.t===1);
 expect(await page.evaluate(()=>__hansch.app.view.y)).toBe('ti');
 await page.click('#ti-open');await expect(page.locator('#ti-body')).toBeVisible();
 expect(requests.filter(p=>p.endsWith('/fragments/ti-body.html'))).toHaveLength(1);
 await expect(page.locator('#ti-rows')).toContainText('measured aggregate');
 await page.click('#ti-t-decide');await expect(page.locator('#ti-decide-body')).toBeVisible();
 const original=await page.locator('#ti-decide-out').innerText();
 await page.selectOption('#tid-act','measured');await page.selectOption('#tid-herg','measured');
 await expect(page.locator('#ti-decide-out')).not.toHaveText(original);
 await expect(page.locator('#ti-decide-steps')).toContainText('measured only');
 await page.click('#ti-decide-reset');
 await page.click('#ti-t-expose');await expect(page.locator('#ti-exp-body')).toBeVisible();
 await page.selectOption('#tix-drug','5702160');
 await expect(page.locator('#ti-exp-out')).toContainText('6.60');
 await expect(page.locator('#ti-exp-out')).toContainText('0.840');
 await expect(page.locator('#ti-exp-out')).toContainText('predicted');
 await expect(page.locator('#ti-exp-out')).toContainText('measured aggregate');
 const margin=page.locator('#ti-exp-out tbody tr').first().locator('[data-label="Margin over hERG"] strong');
 const initial=Number((await margin.innerText()).replace('−','-'));
 const dose=page.locator('#tix-dose');await dose.fill(String(Number(await dose.inputValue())*2));await dose.press('Tab');
 await expect.poll(async()=>Number((await margin.innerText()).replace('−','-'))).toBeCloseTo(initial-Math.log10(2),1);
 await expect(page.locator('#ti-exp-out')).toContainText('not a safety threshold');expect(errors).toEqual([]);
});
test('famotidine bench and route table retain legacy numbers with adjacent limitations',async({page})=>{
 await ready(page);await famotidine(page);await page.click('#d-bench-open');
 await expect(page.locator('#d-bench')).toContainText('3.06');await expect(page.locator('#d-bench')).toContainText('4.90');
 await expect(page.locator('#d-bench')).toContainText('unit-dependent');
 await page.locator('#table-details').evaluate(el=>el.open=true);
 await page.check('#t-extra');await page.check('#t-permode');
 const rows=page.locator('#table tbody tr[data-cid="5702160"]');await expect(rows).toHaveCount(2);
 await expect(rows.filter({hasText:/oral/i})).toContainText('3.23');
 await expect(rows.filter({hasText:/oral/i})).toContainText('3.1');
 await expect(rows.filter({hasText:/intravenous/i})).toContainText('7.2');
 await expect(page.locator('#t-note')).toContainText('Neither is validated');
});
test('standalone lab retains famotidine numeric expressions and labels their limitations',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto('/lab/');
 await page.waitForFunction(()=>document.querySelectorAll('#names option').length>0);
 await page.locator('#q').fill('famotidine');await page.locator('#q').press('Tab');
 await expect(page.locator('#cardName')).toHaveText('famotidine');
 await expect(page.locator('#oFc')).toHaveText('3.06');await expect(page.locator('#oTi')).toHaveText('4.90');
 await expect(page.locator('#warn')).toContainText('not a therapeutic index or safety ranking');expect(errors).toEqual([]);
});
